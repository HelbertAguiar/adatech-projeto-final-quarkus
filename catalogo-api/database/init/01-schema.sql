-- Apenas para a demonstracao Docker: executa na primeira criacao do volume.
-- Em sistemas reais, gerenciar schema com Flyway ou Liquibase.
CREATE TABLE IF NOT EXISTS agendamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sala BIGINT NOT NULL,
    id_usuario BIGINT,
    uf VARCHAR(2) NOT NULL,
    data DATE NOT NULL,
    periodo VARCHAR(20) NOT NULL,
    CONSTRAINT agendamentos_data_valida CHECK (data >= CURRENT_DATE)
);
