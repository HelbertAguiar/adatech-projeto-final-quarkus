-- Apenas para a demonstracao Docker: executa na primeira criacao do volume.
-- Em sistemas reais, gerenciar schema com Flyway ou Liquibase.
CREATE TABLE IF NOT EXISTS produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    preco NUMERIC(10, 2) NOT NULL,
    quantidade INTEGER NOT NULL,
    CONSTRAINT produtos_preco_positivo CHECK (preco > 0),
    CONSTRAINT produtos_quantidade_nao_negativa CHECK (quantidade >= 0)
);
